#!/usr/bin/env python3
"""Generates src/aegis/editor/ui/lucide.cppm, the codepoints of the Lucide icon font, from content/fonts/Lucide.ttf.

  tools/update-lucide.py              regenerates the module from the committed font (checks its sha256 first)
  tools/update-lucide.py <version>    e.g. tools/update-lucide.py 1.61.0: downloads that lucide-static release's
                                      font and license into content/fonts/, then regenerates the module

Needs fontTools (pip install fonttools). On Windows, run it with `python tools/update-lucide.py`.

The module, the editor's internal partition aegis.editor:lucide, names every icon after its glyph in the font's post
table (mouse-pointer-2 -> mousePointer2) in aegis::editor::lucide; theme::icons in :theme gives the ones the editor
uses its own names. Only the private-use area is listed: the editor merges just that range into its UI font
(theme.cpp), and the font's letters and digits are no icons. content/fonts/Lucide-VERSION.txt records the package and
version, the font's URL and its sha256, so a rerun without arguments reproduces the module. The font and its license
stay byte for byte as upstream ships them.

Commit an update on its own ("Update Lucide to <version>"). An icon the new release renamed or dropped is a compile
error at its alias in theme.cppm.
"""

import hashlib
import logging
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "content" / "fonts"
FONT = FONTS / "Lucide.ttf"
LICENSE = FONTS / "Lucide-LICENSE.txt"
VERSION = FONTS / "Lucide-VERSION.txt"
MODULE = ROOT / "src" / "aegis" / "editor" / "ui" / "lucide.cppm"

PACKAGE = "lucide-static"
PRIVATE_USE = range(0xE000, 0xF900)

# C++ keywords and alternative tokens a glyph name could become; such names, and those starting with a digit, get
# a '_' in front.
CPP_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break", "case", "catch",
    "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept", "const", "consteval", "constexpr",
    "constinit", "const_cast", "continue", "co_await", "co_return", "co_yield", "decltype", "default", "delete",
    "do", "double", "dynamic_cast", "else", "enum", "explicit", "export", "extern", "false", "float", "for",
    "friend", "goto", "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
    "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register", "reinterpret_cast",
    "requires", "return", "short", "signed", "sizeof", "static", "static_assert", "static_cast", "struct",
    "switch", "template", "this", "thread_local", "throw", "true", "try", "typedef", "typeid", "typename", "union",
    "unsigned", "using", "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
}


def fail(message):
    sys.exit(f"error: {message}")


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def font_url(version):
    return f"https://unpkg.com/{PACKAGE}@{version}/font/lucide.ttf"


def download(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def identifier(glyph):
    """The C++ name of a glyph: kebab-case to camelCase, '_' in front of a keyword or a leading digit."""
    parts = glyph.split("-")
    name = parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])
    if not re.fullmatch(r"[A-Za-z0-9_]+", name):
        fail(f"glyph '{glyph}' makes no C++ name")
    if name[0].isdigit() or name in CPP_KEYWORDS:
        name = "_" + name
    return name


def icons(font_path):
    """The private-use icons as {C++ name: (codepoint, glyph name)}, a glyph on several codepoints at the lowest."""
    from fontTools.ttLib import TTFont

    logging.getLogger("fontTools").setLevel(logging.ERROR)  # Lucide's post table has 2 stray bytes
    cmap = TTFont(font_path).getBestCmap()
    lowest = {}
    for codepoint, glyph in sorted(cmap.items()):
        if codepoint in PRIVATE_USE:
            lowest.setdefault(glyph, codepoint)

    named = {}
    for glyph, codepoint in lowest.items():
        name = identifier(glyph)
        if name in named:
            fail(f"glyphs '{named[name][1]}' and '{glyph}' both make '{name}'")
        named[name] = (codepoint, glyph)
    return named


def literal(codepoint):
    """The C++ string literal of a codepoint, as a universal character name."""
    return '"' + "\\" + f'u{codepoint:04X}"'


def write_module(version):
    first = literal(0xE000)
    lines = [
        "// AUTO-GENERATED FILE - DO NOT EDIT",
        f"// Generated by tools/update-lucide.py from Lucide {version} ({PACKAGE}).",
        "//",
        "// Every icon of content/fonts/Lucide.ttf as UTF-8 named after its glyph.",
        "",
        "module aegis.editor:lucide;",
        "",
        "// U+E000 must encode as UTF-8's EE 80 80 (MSVC needs /utf-8)",
        f"static_assert(sizeof({first}) == 4 && {first}[0] == '\\xEE' && {first}[1] == '\\x80' && {first}[2] == '\\x80', "
        '"the icons need UTF-8 string literals");',
        "",
        "namespace aegis::editor::lucide",
        "{",
        "// clang-format off",
    ]
    named = icons(FONT)
    for name, (codepoint, glyph) in sorted(named.items()):
        lines.append(f"inline constexpr const char* {name} = {literal(codepoint)}; // {glyph}")
    lines += ["// clang-format on", "}", ""]
    MODULE.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {MODULE.relative_to(ROOT).as_posix()}: {len(named)} icons of Lucide {version}")


def read_version():
    """The version recorded in Lucide-VERSION.txt, after checking the committed font against its hash."""
    try:
        package, url, digest = VERSION.read_text(encoding="utf-8").split()
    except (OSError, ValueError):
        fail(f"{VERSION.relative_to(ROOT).as_posix()} is missing or not '<package>@<version>', '<url>', '<sha256>'")
    name, _, version = package.partition("@")
    if name != PACKAGE or url != font_url(version):
        fail(f"{VERSION.relative_to(ROOT).as_posix()} names {package} at {url}, not a {PACKAGE} font")
    if sha256(FONT.read_bytes()) != digest:
        fail(f"{FONT.relative_to(ROOT).as_posix()} is not the {package} font {VERSION.name} records "
             f"(sha256 {digest}); run tools/update-lucide.py <version>")
    return version


def update(version):
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        fail(f"'{version}' is no release version like 1.61.0")
    url = font_url(version)
    try:
        font = download(url)
        license_text = download(f"https://unpkg.com/{PACKAGE}@{version}/LICENSE")
    except OSError as error:
        fail(f"downloading {PACKAGE}@{version}: {error}")
    FONT.write_bytes(font)
    LICENSE.write_bytes(license_text)
    VERSION.write_text(f"{PACKAGE}@{version}\n{url}\n{sha256(font)}\n", encoding="utf-8", newline="\n")
    print(f"wrote {PACKAGE}@{version} into {FONTS.relative_to(ROOT).as_posix()}/")


def main(args):
    if len(args) > 1 or (args and args[0].startswith("-")):
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        print("Needs fontTools (pip install fonttools).", file=sys.stderr)
        sys.exit(2)
    try:
        import fontTools  # noqa: F401
    except ImportError:
        fail("needs fontTools: pip install fonttools")
    if args:
        update(args[0])
    write_module(read_version())


if __name__ == "__main__":
    main(sys.argv[1:])
